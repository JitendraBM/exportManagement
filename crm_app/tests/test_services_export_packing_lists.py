class TestReads:
    def test_list_all_is_tenant_scoped(self, container, seed):
        product = make_product(container, seed, "GVT 600X1200", "69072100")
        make_export(container, seed, [item_for(product, 100)])
        other = container.tenant_repo.create("Other Co", "other")
        assert len(container.export_packing_list_service.list_all(seed.company_id)) == 1
        assert container.export_packing_list_service.list_all(other.id) == []

    def test_get_is_tenant_scoped(self, container, seed):
        from app.exceptions import NotFoundError
        product = make_product(container, seed, "GVT 600X1200", "69072100")
        invoice = make_export(container, seed, [item_for(product, 100)])
        packing_list = packing_list_for(container, seed, invoice)
        other = container.tenant_repo.create("Other Co", "other")
        with pytest.raises(NotFoundError):
            container.export_packing_list_service.get(packing_list.id, other.id)

    def test_the_parent_invoice_is_attached_for_the_printed_header(self, container, seed):
        product = make_product(container, seed, "GVT 600X1200", "69072100")
        invoice = make_export(container, seed, [item_for(product, 100)])
        got = container.export_packing_list_service.get(
            packing_list_for(container, seed, invoice).id, seed.company_id
        )
        assert got.invoice is not None
        assert got.invoice.export_invoice_number == invoice.export_invoice_number
